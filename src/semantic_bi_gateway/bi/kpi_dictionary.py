"""Deterministic Markdown KPI dictionary generator from compiled semantic catalog."""

from __future__ import annotations

from semantic_bi_gateway.semantic.models import CompiledSemanticModel


def render_kpi_dictionary(compiled: CompiledSemanticModel) -> str:
    """Render deterministic Markdown KPI dictionary referencing certified metrics and lineage."""
    certified_metrics = [
        compiled.metrics[name]
        for name in sorted(compiled.metrics)
        if compiled.metrics[name].certified
    ]

    lines: list[str] = [
        "# Certified KPI Dictionary",
        "",
        "> **Auto-generated by `semantic-bi-nl2sql-gateway` (`ADR-003`).** "
        "Do not edit manually; source of truth is `catalog/metrics.yaml` + compiled dbt models.",
        "",
        f"- **Project:** `{compiled.project_name}`",
        f"- **Catalog Version:** `{compiled.schema_version}` | **Dialect:** `{compiled.default_dialect}`",
        f"- **Certified KPIs:** `{len(certified_metrics)}` | **Semantic Models:** `{len(compiled.models)}`",
        "",
        "---",
        "",
        "## Summary Matrix",
        "",
        "| KPI | DAX Measure | Base Model | Type | Format | Time Intelligence | Target | Owner |",
        "| :--- | :--- | :--- | :---: | :---: | :---: | :---: | :--- |",
    ]

    for metric in certified_metrics:
        ti = "YTD, YoY %, MoM %, R12M" if metric.time_intelligence else "No"
        has_target = "Yes" if metric.target_expression else "No"
        lines.append(
            f"| `{metric.name}` | `[{metric.label}]` | `{metric.model}` | `{metric.metric_type}` | "
            f"`{metric.format}` | {ti} | {has_target} | {metric.owner} |"
        )

    lines.extend(["", "---", "", "## Detailed KPI Specifications", ""])

    for metric in certified_metrics:
        model_spec = compiled.models[metric.model]
        sql_formula = (
            metric.expression
            or f"({metric.numerator}) / NULLIF({metric.denominator}, 0)"
        )
        dims = ", ".join(f"`{dim}`" for dim in metric.dimensions)
        synonyms = ", ".join(f"`{syn}`" for syn in metric.synonyms) if metric.synonyms else "—"
        target_text = f"`{metric.target_expression}`" if metric.target_expression else "—"

        lines.extend(
            [
                f"### {metric.label} (`{metric.name}`)",
                "",
                f"- **Description:** {metric.description}",
                f"- **dbt Base Model / Table:** `{metric.model}` (`{model_spec.table}`)",
                f"- **Model Grain:** {model_spec.grain}",
                f"- **SQL Formula:** `{sql_formula}`",
                f"- **DAX Measure:** `' _Measures'[{metric.label}]`".replace("' _Measures'", "'_Measures'"),
                f"- **Target Expression:** {target_text}",
                f"- **Display Folder:** `{metric.display_folder or 'KPIs'}`",
                f"- **Allowed Dimensions:** {dims}",
                f"- **Bilingual Synonyms (PT/EN):** {synonyms}",
                f"- **Owner:** {metric.owner}",
                "",
            ]
        )

    return "\n".join(lines)
